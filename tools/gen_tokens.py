"""Generate NocturneTokens.kt and nocturne_colors.xml from design-system/nocturne.tokens.json.

Usage: python -I tools/gen_tokens.py [--check]
--check regenerates in memory and exits 1 if a committed output differs.
Stdlib only. Fails (exit 1, token path in the message) on identifier collisions,
unresolvable references, missing/empty $value and unknown $type; never emits a default.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design-system" / "nocturne.tokens.json"
KT_OUT = ROOT / "android/app/src/main/java/app/palm/core/designsystem/NocturneTokens.kt"
XML_OUT = ROOT / "android/app/src/main/res/values/nocturne_colors.xml"
HEADER = "// GENERATED by tools/gen_tokens.py from design-system/nocturne.tokens.json - do not edit"
REF = re.compile(r"^\{([^{}]+)\}$")
KNOWN_TYPES = {"color", "dimension", "fontFamily", "typography", "shadow", "gradient", "duration", "cubicBezier"}


class TokenError(Exception):
    pass


def pascal(key):
    parts = [p for p in re.split(r"[-_ ]+", key) if p]
    return "".join(p[0].upper() + p[1:].lower() for p in parts)


def collect(data):
    """Return tokens in file order: [(path_tuple, type, value)]."""
    out = []

    def walk(node, path, inherited):
        typ = node.get("$type", inherited)
        if "$value" in node:
            val = node["$value"]
            if val is None or val == "" or val == [] or val == {}:
                raise TokenError(f"{'.'.join(path)}: empty $value")
            if typ is None:
                raise TokenError(f"{'.'.join(path)}: no $type on the token or any parent group")
            if typ not in KNOWN_TYPES:
                raise TokenError(f"{'.'.join(path)}: unknown $type '{typ}'")
            out.append((path, typ, val))
            return
        children = [(k, v) for k, v in node.items() if not k.startswith("$")]
        if path and not children:
            raise TokenError(f"{'.'.join(path)}: missing $value")
        for k, v in children:
            if not isinstance(v, dict):
                raise TokenError(f"{'.'.join(path + (k,))}: not a token or group")
            walk(v, path + (k,), typ)

    walk(data, (), None)
    return out


def placement(path, typ):
    """(Kotlin object, identifier) for a token."""
    if typ == "color":
        obj = "NocturneColors" if path[0] == "color" else "Nocturne" + pascal(path[0])
        rest = path[1:]
    elif typ == "dimension":
        obj, rest = "Nocturne" + pascal(path[1]), path[2:]
    else:
        obj = {"fontFamily": "NocturneFontRole", "typography": "NocturneTypeSpecs", "shadow": "NocturneShadows",
               "gradient": "NocturneGradients", "duration": "NocturneDurations", "cubicBezier": "NocturneEasings"}[typ]
        rest = path[2:] if typ == "fontFamily" else path[1:]
    ident = "".join(pascal(p) for p in rest)
    if not ident:
        raise TokenError(f"{'.'.join(path)}: cannot derive an identifier")
    if ident[0].isdigit():
        ident = path[-2][0].upper() + ident  # space.2 -> S2
    return obj, ident


def num(text, unit, where):
    s = str(text)
    if not s.endswith(unit):
        raise TokenError(f"{where}: expected a '{unit}' value, got '{s}'")
    try:
        return float(s[: -len(unit)] if unit else s)
    except ValueError:
        raise TokenError(f"{where}: not a number: '{s}'") from None


def kf(x):
    x = float(x)
    return f"{int(x)}f" if x == int(x) else f"{x!r}f"


def kdp(x):
    x = float(x)
    n = str(int(x)) if x == int(x) else repr(x)
    return f"({n}).dp" if x < 0 else f"{n}.dp"


def argb(hexstr, where):
    m = re.fullmatch(r"#([0-9A-Fa-f]{6})([0-9A-Fa-f]{2})?", str(hexstr))
    if not m:
        raise TokenError(f"{where}: not a #RRGGBB or #RRGGBBAA colour: '{hexstr}'")
    return ((m.group(2) or "FF") + m.group(1)).upper()  # CSS RRGGBBAA -> ARGB


class Gen:
    def __init__(self, data):
        self.tokens = collect(data)
        self.by_path = {".".join(p): (p, t, v) for p, t, v in self.tokens}
        self.place = {}
        seen = {}
        for p, t, _ in self.tokens:
            key = placement(p, t)
            dotted = ".".join(p)
            if key in seen:
                raise TokenError(f"identifier collision {key[0]}.{key[1]}: {seen[key]} and {dotted}")
            seen[key] = dotted
            self.place[dotted] = key
        for key in (("NocturneColors", "ByPath"), ("NocturneTypeSpecs", "ByName")):
            if key in seen:
                raise TokenError(f"{seen[key]}: identifier {key[1]} is reserved for a generated map")

    def target(self, ref, where, stack=()):
        if ref not in self.by_path:
            raise TokenError(f"{where}: unresolvable reference {{{ref}}}")
        if ref in stack:
            raise TokenError(f"{where}: reference cycle through {{{ref}}}")
        p, t, v = self.by_path[ref]
        m = REF.match(v) if isinstance(v, str) else None
        if m:
            self.target(m.group(1), ref, stack + (ref,))
        return p, t, v

    def color(self, v, where):
        m = REF.match(v) if isinstance(v, str) else None
        if m:
            p, t, _ = self.target(m.group(1), where)
            if t != "color":
                raise TokenError(f"{where}: {{{m.group(1)}}} is not a color")
            return ".".join(self.place[".".join(p)])
        return f"Color(0x{argb(v, where)})"

    def color_hex(self, v, where):
        m = REF.match(v) if isinstance(v, str) else None
        if m:
            tp, _, tv = self.target(m.group(1), where)
            return self.color_hex(tv, ".".join(tp))
        return "#" + argb(v, where)

    def deref(self, v, where):
        m = REF.match(v) if isinstance(v, str) else None
        return self.target(m.group(1), where)[2] if m else v

    def field(self, d, key, where):
        if not isinstance(d, dict) or key not in d or d[key] in (None, ""):
            raise TokenError(f"{where}: missing '{key}'")
        return self.deref(d[key], where)

    def expr(self, p, t, v):
        where = ".".join(p)
        if t == "color":
            return self.color(v, where)
        m = REF.match(v) if isinstance(v, str) else None
        if m:
            tp, tt, _ = self.target(m.group(1), where)
            if tt != t:
                raise TokenError(f"{where}: {{{m.group(1)}}} is a {tt}, expected {t}")
            return ".".join(self.place[".".join(tp)])
        if t == "dimension":
            return kdp(num(v, "px", where))
        if t == "duration":
            return str(int(num(v, "ms", where)))
        if t == "cubicBezier":
            if not isinstance(v, list) or len(v) != 4:
                raise TokenError(f"{where}: cubicBezier needs 4 numbers")
            return "CubicBezierEasing(" + ", ".join(kf(x) for x in v) + ")"
        if t == "typography":
            fam = v.get("fontFamily") if isinstance(v, dict) else None
            fm = REF.match(fam) if isinstance(fam, str) else None
            if not fm:
                raise TokenError(f"{where}: fontFamily must reference a font.family token")
            fp, ft, _ = self.target(fm.group(1), where)
            if ft != "fontFamily":
                raise TokenError(f"{where}: {{{fm.group(1)}}} is not a fontFamily")
            role = "NocturneFontRole." + self.place[".".join(fp)][1]
            weight = int(self.field(v, "fontWeight", where))
            size = num(self.field(v, "fontSize", where), "px", where)
            lh = num(self.field(v, "lineHeight", where), "px", where)
            ls = num(self.field(v, "letterSpacing", where), "em", where)
            return f"NocturneTypeSpec({role}, {weight}, {kf(size)}, {kf(lh)}, {kf(ls)})"
        if t == "shadow":
            if not isinstance(v, dict) or v.get("color") in (None, ""):
                raise TokenError(f"{where}: missing 'color'")
            c = self.color(v["color"], where)
            dims = [kdp(num(self.field(v, k, where), "px", where)) for k in ("offsetX", "offsetY", "blur", "spread")]
            return f"NocturneShadow({c}, {', '.join(dims)})"
        if t == "gradient":
            if not isinstance(v, list):
                raise TokenError(f"{where}: gradient needs a list of stops")
            stops = []
            for i, s in enumerate(v):
                w = f"{where}[{i}]"
                if not isinstance(s, dict) or "color" not in s or "position" not in s:
                    raise TokenError(f"{w}: stop needs color and position")
                stops.append(f"{kf(s['position'])} to {self.color(s['color'], w)}")
            return "arrayOf(" + ", ".join(stops) + ")"
        raise TokenError(f"{where}: unknown $type '{t}'")

    def kotlin(self):
        objects = {}  # object name -> [lines], file order of first appearance
        for p, t, v in self.tokens:
            obj, ident = self.place[".".join(p)]
            lines = objects.setdefault(obj, [])
            if t == "fontFamily":
                if not isinstance(v, str):
                    raise TokenError(f"{'.'.join(p)}: fontFamily must be a string")
                lines.append(f'{ident}("{v}")')
            else:
                kw = "const val" if t == "duration" else "val"
                lines.append(f"{kw} {ident} = {self.expr(p, t, v)}")
        out = [HEADER, "package app.palm.core.designsystem", "",
               "import androidx.compose.animation.core.CubicBezierEasing",
               "import androidx.compose.ui.graphics.Color",
               "import androidx.compose.ui.unit.Dp",
               "import androidx.compose.ui.unit.dp", ""]
        for obj, lines in objects.items():
            if obj == "NocturneFontRole":
                out.append("enum class NocturneFontRole(val family: String) {")
                out.append(",\n".join("    " + l for l in lines) + ",")
                out += ["}", ""]
                continue
            if obj == "NocturneTypeSpecs":
                out += ["data class NocturneTypeSpec(val role: NocturneFontRole, val weight: Int, val sizeSp: Float, "
                        "val lineHeightSp: Float, val letterSpacingEm: Float)", ""]
            if obj == "NocturneShadows":
                out += ["data class NocturneShadow(val color: Color, val offsetX: Dp, val offsetY: Dp, val blur: Dp, "
                        "val spread: Dp)", ""]
            out.append(f"object {obj} {{")
            out += ["    " + l for l in lines]
            if obj == "NocturneColors":  # token path -> colour, file order (showcase swatches)
                pairs = [f'        "{".".join(p[1:])}" to {self.place[".".join(p)][1]},'
                         for p, t, _ in self.tokens if t == "color" and p[0] == "color"]
                out += ["", "    val ByPath: Map<String, Color> = linkedMapOf(", *pairs, "    )"]
            if obj == "NocturneTypeSpecs":  # token name ("Display XL") -> spec, file order
                pairs = [f'        "{" ".join(p[1:])}" to {self.place[".".join(p)][1]},'
                         for p, t, _ in self.tokens if t == "typography"]
                out += ["", "    val ByName: Map<String, NocturneTypeSpec> = linkedMapOf(", *pairs, "    )"]
            out += ["}", ""]
        return "\n".join(out).rstrip("\n") + "\n"

    def xml(self):
        out = ['<?xml version="1.0" encoding="utf-8"?>',
               "<!-- GENERATED by tools/gen_tokens.py from design-system/nocturne.tokens.json - do not edit -->",
               "<resources>"]
        names = {}
        for p, t, v in self.tokens:
            if t != "color" or p[0] != "color":
                continue
            name = "nocturne_" + "_".join(x.replace("-", "_").lower() for x in p[1:])
            if name in names:
                raise TokenError(f"colour resource collision {name}: {names[name]} and {'.'.join(p)}")
            names[name] = ".".join(p)
            out.append(f'    <color name="{name}">{self.color_hex(v, ".".join(p))}</color>')
        out.append("</resources>")
        return "\n".join(out) + "\n"


def generate(data):
    g = Gen(data)
    return g.kotlin(), g.xml()


def main(argv):
    check = "--check" in argv
    try:
        kt, xml = generate(json.loads(TOKENS.read_text(encoding="utf-8")))
    except TokenError as e:
        print(f"gen_tokens: error: {e}", file=sys.stderr)
        return 1
    stale = []
    for path, text in ((KT_OUT, kt), (XML_OUT, xml)):
        if check:
            cur = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
            if cur != text:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print("gen_tokens: stale (run python -I tools/gen_tokens.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    print("gen_tokens: up to date" if check else f"gen_tokens: wrote {KT_OUT.name}, {XML_OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
